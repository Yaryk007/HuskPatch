import SwiftUI

/// The green Android head from the boot animation, traced from the concept video.
/// Points are stored as flat x, y pairs, normalised to the logo's width.
struct AndroidLogoShape: Shape {
    /// height / width of the logo.
    static let aspect: CGFloat = 0.8902

    func path(in rect: CGRect) -> Path {
        var path = Path()
        for data in [Self.outline, Self.eye] {
            var i = 0
            while i + 1 < data.count {
                let point = CGPoint(
                    x: rect.minX + CGFloat(data[i]) * rect.width,
                    y: rect.minY + CGFloat(data[i + 1]) * rect.width
                )
                if i == 0 {
                    path.move(to: point)
                } else {
                    path.addLine(to: point)
                }
                i += 2
            }
            path.closeSubpath()
        }
        return path
    }

