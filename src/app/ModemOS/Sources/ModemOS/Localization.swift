        case .english: return english
        case .ukrainian: return ukrainian[english] ?? english
        case .spanish: return spanish[english] ?? english
        case .german: return german[english] ?? english
        case .french: return french[english] ?? english
        case .italian: return italian[english] ?? english
        case .portuguese: return portuguese[english] ?? english
        case .polish: return polish[english] ?? english
        case .japanese: return japanese[english] ?? english
        }
    }

