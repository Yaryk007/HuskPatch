"""Binder transaction codes from AOSP's .aidl files: the header Android translation's services are written against.

A code is FIRST_CALL_TRANSACTION (1) plus the method's place in the interface or the id the file gives it, so it changes
between Android versions and is never typed by hand. Usage: tools/aidl-codes.py [branch] > husk-tl-aidl-codes.h
"""
import base64, re, sys, urllib.request

BASE = "https://android.googlesource.com/platform/frameworks/base/+/refs/heads/"
FILES = [
    "core/java/android/os/IBatteryPropertiesRegistrar.aidl",
    "core/java/android/os/IPowerManager.aidl",
    "core/java/android/os/IThermalService.aidl",
    "core/java/android/app/IUiModeManager.aidl",
    "location/java/android/location/ICountryDetector.aidl",
]

def methods(text):
    """[(name, code)] in the order the file declares them."""
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    # annotations, with arguments that may hold parentheses in strings
    text = re.sub(r"@\w+(\.\w+)*\s*(\((?:[^()\"]|\"[^\"]*\"|\([^()]*\))*\))?", " ", text)
    body = text[text.index("{", re.search(r"\binterface\s+\w+", text).end()) + 1:text.rindex("}")]
    # nested types are not methods
    while True:
        nested, n = re.subn(r"\b(enum|parcelable|union|interface)\s+\w+\s*\{[^{}]*\}", " ", body)
        if not n: break
        body = nested
    out, index = [], 0
    for stmt in body.split(";"):
        stmt = " ".join(stmt.split())
        if not stmt or stmt.startswith("const ") or "(" not in stmt: continue
        m = re.match(r"(?:oneway )?[\w.<>\[\], ]+?\s(\w+)\s*\((.*)\)\s*(?:=\s*(\d+))?$", stmt)
        if not m: raise SystemExit("cannot read: " + stmt)
        index += 1
        # "= N" is an id, not the code: the generated stub adds FIRST_CALL_TRANSACTION, as it does to the place in the file
        out.append((m.group(1), int(m.group(3)) + 1 if m.group(3) else index))
    return out

def fetch(branch, path):
    with urllib.request.urlopen(BASE + branch + "/" + path + "?format=TEXT", timeout=30) as r:
        return base64.b64decode(r.read()).decode()

if __name__ == "__main__":
    branch = sys.argv[1] if len(sys.argv) > 1 else "android16-release"
    print("/* SPDX-License-Identifier: GPL-2.0-or-later */")
    print("/* Generated by tools/aidl-codes.py from AOSP " + branch + ". Do not edit. */")
    print("#ifndef HUSK_TL_AIDL_CODES_H\n#define HUSK_TL_AIDL_CODES_H\n")
    for path in FILES:
        name = path.rsplit("/", 1)[1][:-5]
        for method, code in methods(fetch(branch, path)):
            print(f"#define AIDL_{name}_{method} {code}u")
        print()
    print("#endif")
